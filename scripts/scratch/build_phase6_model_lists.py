"""Build the model lists for the Phase 6 eval-only items (checklist Phase 6).

Read-only with respect to the Hub: enumerates both project namespaces with
`list_models(author=...)` (never `search=`, per CLAUDE.md), downloads nothing,
uploads nothing. Writes three newline-delimited checkpoint lists into
`sweeps/eval_pt/phase6/` for `scripts/eval_language_model_multi_temperature.py`:

  models_phase6_2_crossdomain_math_contaminated.txt
      6.2 cross-domain transfer: the paper's five sizes, ot=1, sbst=1.0, every
      replica level including the R=0 baseline, to be evaluated on GSM8K.
  models_phase6_3_perturbed_control.txt
      6.3 perturbed positive control: every checkpoint pretrained with a
      perturbed or rephrased contaminant (the `_cont_*` ablation arms).
      ⚠️ These exist ONLY as local directories under models/pt_language_model/
      in the original repo root -- verified 2026-08-17 that neither Hub
      namespace has any `_cont_*` checkpoint -- so the list carries absolute
      local paths, which vLLM loads directly.
  models_phase6_4_passk_uncontaminated.txt
      6.4 pass@k capability floors: R=0, ot=1, one checkpoint per size.

Usage:
    python scripts/scratch/build_phase6_model_lists.py
"""

import pathlib
import re

from huggingface_hub import HfApi

REPO_ROOT = pathlib.Path(__file__).resolve().parent.parent.parent
OUT_DIR = REPO_ROOT / "sweeps" / "eval_pt" / "phase6"

NAMESPACES = ["RylanSchaeffer", "jkazdan"]

# The five sizes the manuscript reports (docs/EXPERIMENT_INVENTORY.md).
PAPER_SIZES = ["34M", "62M", "93M", "153M", "344M"]

NAME_RE = re.compile(
    r"mem_Qwen3-(?P<size>[\d.]+[MB])_"
    r"(?P<benchmark>.+?)_"
    r"rep_(?P<rep>[\d.]+)_"
    r"sbst_(?P<sbst>[\d.]+)_"
    r"epch_(?P<epch>[\d.]+)_"
    r"ot_(?P<ot>[\d.]+)"
    r"(?P<tail>_.+)?$"
)


def enumerate_checkpoints() -> list[dict]:
    api = HfApi()
    rows = []
    for namespace in NAMESPACES:
        for model in api.list_models(author=namespace):
            base = model.id.split("/", 1)[1]
            match = NAME_RE.match(base)
            if match is None:
                continue
            fields = match.groupdict()
            rows.append(
                {
                    "id": model.id,
                    "size": fields["size"],
                    "benchmark": fields["benchmark"],
                    "rep": float(fields["rep"]),
                    "sbst": float(fields["sbst"]),
                    "ot": float(fields["ot"]),
                    "tail": fields["tail"] or "",
                }
            )
    return rows


def dedup(rows: list[dict], key_fn) -> list[dict]:
    """Keep the shortest id per key: `ot_1` and `ot_1.000` are the same cell."""
    best: dict = {}
    for row in rows:
        key = key_fn(row)
        if key not in best or len(row["id"]) < len(best[key]["id"]):
            best[key] = row
    return sorted(
        best.values(), key=lambda r: (float(r["size"][:-1]), r["rep"], r["ot"])
    )


def write_list(path: pathlib.Path, header: str, rows: list[dict]) -> None:
    lines = [header.rstrip(), ""]
    lines += [row["id"] for row in rows]
    path.write_text("\n".join(lines) + "\n")
    print(f"wrote {len(rows):>3} checkpoints -> {path.relative_to(REPO_ROOT)}")


def main() -> None:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    rows = enumerate_checkpoints()
    print(f"{len(rows)} convention-matching checkpoints across {NAMESPACES}")

    # 6.2: MATH-contaminated ladder (plain minerva_math contaminant, no SFT, no
    # _cont_* arm), paper sizes, ot=1, full subset fraction, all replica levels.
    crossdomain = dedup(
        [
            r
            for r in rows
            if r["size"] in PAPER_SIZES
            and r["benchmark"] == "minerva_math"
            and r["tail"] == ""
            and r["ot"] == 1.0
            and r["sbst"] == 1.0
        ],
        key_fn=lambda r: (r["size"], r["rep"]),
    )
    write_list(
        OUT_DIR / "models_phase6_2_crossdomain_math_contaminated.txt",
        "# Phase 6.2 cross-domain transfer: MATH-contaminated ladder (ot=1,\n"
        "# sbst=1.0, incl. R=0 baselines), to be evaluated on GSM8K.\n"
        "# Generated by scripts/scratch/build_phase6_model_lists.py.",
        crossdomain,
    )

    # 6.3: the contaminant-ablation arms (rephrased / perturbed injections).
    # Not on the Hub (verified: zero `_cont_*` ids in either namespace); the
    # sweeps that trained them (`mxamktp0`, `vrxwx4dz`) saved locally only.
    local_models_dir = (
        pathlib.Path(
            "/lfs/skampere1/0/rschaef/KoyejoLab-Scoring-vs-Sampling-Memorization"
        )
        / "models"
        / "pt_language_model"
    )
    ablation = sorted(
        str(path)
        for path in local_models_dir.glob("mem_Qwen3-*_cont_*")
        if (path / "model.safetensors").exists()
    )
    lines = [
        "# Phase 6.3 perturbed positive control: checkpoints pretrained with a",
        "# perturbed or rephrased contaminant (`_cont_*` ablation arms).",
        "# The missing manuscript cell is the perturbed arm at R=316.",
        "# LOCAL PATHS: these checkpoints were never pushed to the Hub; vLLM",
        "# loads the directories directly. Generated by",
        "# scripts/scratch/build_phase6_model_lists.py.",
        "",
    ] + ablation
    out_path = OUT_DIR / "models_phase6_3_perturbed_control.txt"
    out_path.write_text("\n".join(lines) + "\n")
    print(f"wrote {len(ablation):>3} checkpoints -> {out_path.relative_to(REPO_ROOT)}")

    # 6.4: pass@k floors -- uncontaminated, compute-optimal, one per size.
    passk = dedup(
        [
            r
            for r in rows
            if r["size"] in PAPER_SIZES
            and r["benchmark"] == "minerva_math"
            and r["tail"] == ""
            and r["rep"] == 0.0
            and r["ot"] == 1.0
            and r["sbst"] == 1.0
        ],
        key_fn=lambda r: r["size"],
    )
    write_list(
        OUT_DIR / "models_phase6_4_passk_uncontaminated.txt",
        "# Phase 6.4 pass@k capability floors: uncontaminated (R=0) ot=1\n"
        "# checkpoints, one per paper size.\n"
        "# Generated by scripts/scratch/build_phase6_model_lists.py.",
        passk,
    )


if __name__ == "__main__":
    main()
