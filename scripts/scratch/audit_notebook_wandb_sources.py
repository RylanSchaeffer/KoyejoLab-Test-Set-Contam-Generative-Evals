"""Audit every analysis notebook: which W&B project and sweeps it reads, and under which
evaluation protocol.

Written because the 0-shot/4-shot confound was only found by accident, and because a notebook can
silently serve a stale cache built from a *different* sweep list than the one written in the file
(`refresh=False` keeps the old hashed file). Both failure modes are invisible from the source
alone, so this cross-checks three things per notebook:

  1. the sweep IDs written in the .py,
  2. the sweep IDs whose md5 matches the cache files actually on disk,
  3. whether those sweeps still resolve in W&B, and how many runs they have.

Any notebook where (1) and (2) disagree is serving data it does not declare.

Usage:
    PROTOCOL_BUFFERS_PYTHON_IMPLEMENTATION=python \
      ./mem_scoring_vs_sampling_env/bin/python scripts/scratch/audit_notebook_wandb_sources.py
"""

import ast
import hashlib
import os
import re
from pathlib import Path

import wandb

NB_ROOT = Path("notebooks")
OUT = Path("docs/NOTEBOOK_DATA_SOURCES.md")


def sweep_list_hash(sweep_ids: list[str]) -> str:
    return hashlib.md5(("sweeps=" + ",".join(sweep_ids)).encode()).hexdigest()


def literal_lists_of_strings(src: str) -> list[list[str]]:
    """Every list-of-string literal assigned in the file, commented-out ones excluded."""
    out = []
    try:
        tree = ast.parse(src)
    except SyntaxError:
        return out
    for node in ast.walk(tree):
        if isinstance(node, (ast.Assign, ast.AnnAssign)):
            val = node.value
            if isinstance(val, ast.List) and val.elts:
                items = [e.value for e in val.elts if isinstance(e, ast.Constant) and isinstance(e.value, str)]
                if items and all(re.fullmatch(r"[a-z0-9]{8}", i) for i in items):
                    out.append(items)
    return out


def commented_sweep_blocks(src: str) -> list[list[str]]:
    """Sweep IDs sitting inside commented-out list literals -- the notebook-11 failure mode."""
    blocks, cur = [], []
    for line in src.splitlines():
        s = line.strip()
        if s.startswith("#"):
            found = re.findall(r'"([a-z0-9]{8})"', s)
            cur.extend(found)
        else:
            if len(cur) >= 2:
                blocks.append(cur)
            cur = []
    if len(cur) >= 2:
        blocks.append(cur)
    return blocks


def main() -> None:
    api = wandb.Api(timeout=60)
    rows = []

    for nb_dir in sorted(NB_ROOT.iterdir()):
        if not nb_dir.is_dir():
            continue
        pys = list(nb_dir.glob("*.py"))
        if not pys:
            continue
        src = pys[0].read_text()

        projects = sorted(set(re.findall(r'wandb_project_path\s*=\s*"([^"]+)"', src)))
        entity_expr = sorted(set(re.findall(r"wandb_username\s*=\s*([^,\n]+)", src)))
        declared = literal_lists_of_strings(src)
        commented = commented_sweep_blocks(src)

        cache_hashes = {p.name.split("_runs_")[0] for p in (nb_dir / "data").glob("*_runs_*")} \
            if (nb_dir / "data").is_dir() else set()

        # Which declared / commented list explains each cache file?
        explained, unexplained = {}, set(cache_hashes)
        for label, lists in (("declared", declared), ("COMMENTED-OUT", commented)):
            for lst in lists:
                h = sweep_list_hash(lst)
                if h in cache_hashes:
                    explained[h] = (label, lst)
                    unexplained.discard(h)

        rows.append(
            dict(
                notebook=nb_dir.name,
                projects=projects,
                entity=entity_expr,
                declared=declared,
                commented=commented,
                explained=explained,
                unexplained=sorted(unexplained),
            )
        )

    # Resolve every sweep we saw against W&B.
    all_sweeps = {}
    for r in rows:
        for lst in r["declared"] + r["commented"]:
            for s in lst:
                all_sweeps.setdefault(s, set()).update(r["projects"])
    print(f"Resolving {len(all_sweeps)} distinct sweep ids against W&B...", flush=True)
    resolved = {}
    for s, projs in all_sweeps.items():
        for p in projs or {"memorization-scoring-vs-sampling-eval"}:
            try:
                sw = api.sweep(f"rylan/{p}/{s}")
                resolved[s] = (p, len(list(sw.runs)))
                break
            except Exception:
                continue
        resolved.setdefault(s, (None, 0))

    lines = [
        "# What each analysis notebook actually reads",
        "",
        "Generated by `scripts/scratch/audit_notebook_wandb_sources.py`. Regenerate after changing",
        "any notebook's sweep list.",
        "",
        "**Why this file exists.** A notebook can declare one sweep list and serve a cache built",
        "from a different one: `src.analyze.download_wandb_project_runs_configs` hashes the sweep",
        "list into the cache filename and, with `refresh=False`, never re-downloads. Notebook 11",
        "did exactly this -- it declares the 4-shot sweeps but its cache was built from the",
        "commented-out 0-shot list above them, which is why Fig. 1 is 0-shot while Table 1 and the",
        "SFT figures are 4-shot. The `MISMATCH` column below is the check for that.",
        "",
        "| Notebook | W&B project(s) | Declared sweeps | Cache actually built from | Status |",
        "|---|---|---|---|---|",
    ]
    for r in rows:
        if not r["projects"] and not r["declared"]:
            continue
        decl = ", ".join("`" + s + "`" for lst in r["declared"] for s in lst) or "—"
        src_desc, status = [], "ok"
        for h, (label, lst) in r["explained"].items():
            src_desc.append(f"{label}: " + ", ".join("`" + s + "`" for s in lst))
            if label != "declared":
                status = "**MISMATCH**"
        if r["unexplained"]:
            src_desc.append(f"{len(r['unexplained'])} cache file(s) match no list in the file")
            status = "**MISMATCH**" if status == "ok" else status
        lines.append(
            f"| `{r['notebook']}` | {', '.join('`'+p+'`' for p in r['projects']) or '—'} | "
            f"{decl} | {'<br>'.join(src_desc) or '—'} | {status} |"
        )

    lines += ["", "## Sweep resolution against W&B (entity `rylan`)", "",
              "| Sweep | Project | Runs |", "|---|---|---|"]
    for s in sorted(resolved):
        p, n = resolved[s]
        lines.append(f"| `{s}` | {p or '**DOES NOT RESOLVE**'} | {n} |")

    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n")
    print(f"Wrote {OUT}")
    gone = [s for s, (p, _) in resolved.items() if p is None]
    print(f"{len(gone)} of {len(resolved)} sweeps do not resolve: {gone}")


if __name__ == "__main__":
    os.chdir(Path(__file__).resolve().parents[2])
    main()
