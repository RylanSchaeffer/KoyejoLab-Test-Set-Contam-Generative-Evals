"""List uncontaminated (R=0) Qwen3 checkpoints on the HF Hub for Phase 0 GSM8K evaluation.

Phase 0 of docs/ICLR_2027_CHECKLIST.md needs every R=0 checkpoint, including the
overtrained ones (ot > 1), because if any clean capability exists in the zoo it is
most likely in the most heavily overtrained models.

Read-only with respect to the Hub: lists models, downloads nothing, uploads nothing.
With --write-models-file it emits a newline-delimited checkpoint list for
scripts/eval_language_model_multi_temperature.py --models-file.

Usage:
    uv run python scripts/scratch/list_uncontaminated_checkpoints.py
    uv run python scripts/scratch/list_uncontaminated_checkpoints.py \
        --write-models-file sweeps/eval_pt/gsm8k/models_phase0_uncontaminated.txt
"""

import argparse
import pathlib
import re
from collections import defaultdict

from huggingface_hub import HfApi

# mem_Qwen3-{size}_{benchmark}_rep_{R}_sbst_{frac}_epch_{E}_ot_{multiplier}[_sft]
# Numeric fields have inconsistent decimal formatting, so parse as float rather
# than string-matching (see CLAUDE.md).
NAME_RE = re.compile(
    r"mem_Qwen3-(?P<size>[\d.]+[MB])_"
    r"(?P<benchmark>.+?)_"
    r"rep_(?P<rep>[\d.]+)_"
    r"sbst_(?P<sbst>[\d.]+)_"
    r"epch_(?P<epch>[\d.]+)_"
    r"ot_(?P<ot>[\d.]+)"
    r"(?P<suffix>_sft)?$"
)

SIZE_ORDER = {
    "34M": 34e6,
    "48M": 48e6,
    "62M": 62e6,
    "63M": 63e6,
    "93M": 93e6,
    "111M": 111e6,
    "138M": 138e6,
    "153M": 153e6,
    "165M": 165e6,
    "191M": 191e6,
    "223M": 223e6,
    "262M": 262e6,
    "344M": 344e6,
    "499M": 499e6,
    "660M": 660e6,
    "806M": 806e6,
    "934M": 934e6,
    "1.09B": 1.09e9,
    "1.26B": 1.26e9,
    "1.44B": 1.44e9,
}


def write_models_file(rows: list[dict], path: pathlib.Path) -> None:
    """Write a deduplicated checkpoint list, one HF id per line.

    Several (size, ot) cells exist twice on the Hub under different numeric
    formatting of the same run -- `ot_1` alongside `ot_1.000`, `sbst_1.0000`
    alongside `sbst_1.000`. They are the same experiment uploaded by different
    sweep generations, so evaluating both wastes GPU time and double-counts the
    cell in any average. Keep the shortest id per (size, ot, sft) cell, which is
    the plain form the existing eval sweeps reference.
    """
    best: dict[tuple[str, float, bool], str] = {}
    for row in rows:
        key = (row["size"], row["ot"], row["sft"])
        current = best.get(key)
        if current is None or len(row["id"]) < len(current):
            best[key] = row["id"]

    ordered = sorted(
        best.items(), key=lambda kv: (kv[0][2], SIZE_ORDER.get(kv[0][0], 0.0), kv[0][1])
    )
    path.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "# Phase 0 of docs/ICLR_2027_CHECKLIST.md: every uncontaminated (R=0)",
        "# checkpoint, for measuring the clean GSM8K capability floor.",
        "# Generated by scripts/scratch/list_uncontaminated_checkpoints.py.",
        "# Deduplicated to one checkpoint per (size, overtrain multiplier, sft) cell.",
        "",
    ]
    last_group = None
    for (size, ot, sft), model_id in ordered:
        group = "sft" if sft else ("compute-optimal" if ot == 1.0 else "overtrained")
        if group != last_group:
            lines.append(f"# --- {group} ---")
            last_group = group
        lines.append(model_id)
    path.write_text("\n".join(lines) + "\n")
    print(f"\nWrote {len(ordered)} deduplicated checkpoints to {path}")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--write-models-file",
        type=pathlib.Path,
        default=None,
        help="Path to write a deduplicated --models-file list for the eval script.",
    )
    args = parser.parse_args()

    api = HfApi()
    rows = []
    all_sizes: defaultdict[str, int] = defaultdict(int)
    authors: defaultdict[str, int] = defaultdict(int)
    unparsed: list[str] = []

    # Enumerate the two project namespaces exhaustively rather than using
    # search=: Hub full-text search is fuzzy (it returns unrelated "meme" models)
    # and cannot be trusted to be exhaustive for a prefix. limit=None defeats the
    # client-side page cap.
    models = []
    for author in ("RylanSchaeffer", "jkazdan"):
        owned = list(api.list_models(author=author, limit=None))
        prefixed = [m for m in owned if m.id.split("/", 1)[1].startswith("mem_Qwen3")]
        scale = [m for m in owned if m.id.split("/", 1)[1].startswith("scale_mem_")]
        print(
            f"{author}: {len(owned)} models total, "
            f"{len(prefixed)} mem_Qwen3*, {len(scale)} scale_mem_*"
        )
        models.extend(prefixed)
    print(f"\nTotal mem_Qwen3* checkpoints in project namespaces: {len(models)}\n")

    for model in models:
        author, _, name = model.id.partition("/")
        authors[author] += 1
        match = NAME_RE.match(name)
        if match is None:
            unparsed.append(model.id)
            continue
        fields = match.groupdict()
        all_sizes[fields["size"]] += 1
        if float(fields["rep"]) != 0.0:
            continue
        if float(fields["sbst"]) != 1.0:
            continue
        rows.append(
            {
                "id": model.id,
                "size": fields["size"],
                "benchmark": fields["benchmark"],
                "ot": float(fields["ot"]),
                "sft": bool(fields["suffix"]),
            }
        )

    print(f"Found {len(rows)} uncontaminated (R=0, sbst=1.0) checkpoints\n")

    by_kind = defaultdict(list)
    for row in rows:
        kind = (
            "sft"
            if row["sft"]
            else ("pretrain_ot1" if row["ot"] == 1.0 else "pretrain_overtrained")
        )
        by_kind[kind].append(row)

    for kind in ("pretrain_ot1", "pretrain_overtrained", "sft"):
        group = by_kind[kind]
        print(f"=== {kind}: {len(group)} ===")
        for row in sorted(
            group, key=lambda r: (SIZE_ORDER.get(r["size"], 0.0), r["ot"])
        ):
            print(f"  ot={row['ot']:>6.3f}  {row['size']:>6}  {row['id']}")
        print()

    sizes = sorted({r["size"] for r in rows}, key=lambda s: SIZE_ORDER.get(s, 0.0))
    print(f"Sizes present among R=0: {', '.join(sizes)}")
    benchmarks = sorted({r["benchmark"] for r in rows})
    print(f"Benchmark fields present: {', '.join(benchmarks)}")

    print(
        "\n=== All sizes across the whole convention-matching zoo (any R, any sbst) ==="
    )
    for size in sorted(all_sizes, key=lambda s: SIZE_ORDER.get(s, 0.0)):
        marker = "" if size in SIZE_ORDER else "  <-- unrecognized size"
        print(f"  {size:>6}: {all_sizes[size]:>4} checkpoints{marker}")
    print("\n=== Authors ===")
    for author in sorted(authors, key=lambda a: -authors[a]):
        print(f"  {author:>24}: {authors[author]:>4}")

    print(f"\nNames not matching the convention: {len(unparsed)}")
    for name in unparsed[:10]:
        print(f"  {name}")

    if args.write_models_file is not None:
        write_models_file(rows, args.write_models_file)


if __name__ == "__main__":
    main()
